fun main() {

    println("Operadores de comparacion en Venta de Motos")
    val precioMotoA = 12000
    val precioMotoB = 8500

    println("Igualdad")
    println("$precioMotoA == $precioMotoB: ${precioMotoA == precioMotoB}")

    println("Desigualdad")
    println("$precioMotoA != $precioMotoB: ${precioMotoA != precioMotoB}")

    println("Mayor que")
    println("$precioMotoA > $precioMotoB: ${precioMotoA > precioMotoB}")

    println("Menor que")
    println("$precioMotoA < $precioMotoB: ${precioMotoA < precioMotoB}")

    println("Mayor o igual que")
    println("$precioMotoA >= $precioMotoB: ${precioMotoA >= precioMotoB}")

    println("Menor o igual que")
    println("$precioMotoA <= $precioMotoB: ${precioMotoA <= precioMotoB}")
}
